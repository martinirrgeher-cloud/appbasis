import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { mkdtemp, mkdir, writeFile, readFile, rm, copyFile, symlink, link, unlink } from "node:fs/promises";
import { promisify } from "node:util";
import { execFile } from "node:child_process";
import {
  verifyK2OfflineMediaRecovery as verify,
  K2OfflineMediaRecoveryError,
} from "./ulc-linz-k2-offline-media-recovery.mjs";
import { encryptM4BackupFile, decryptM4BackupFile } from "./m4-backup-crypto.mjs";

const exec = promisify(execFile);
const KEY = "a".repeat(64);
const SNAP = "ulc-private-media-test-snapshot-1";
const KEY_ONE = "exercise-catalog/ulc-linz/exercise-1/media-1";
const KEY_TWO = "exercise-catalog/ulc-linz/exercise-2/media-2";
const B1 = Buffer.from("a short, original test-only private exercise video");
const B2 = Buffer.from([0, 1, 2, 0, 255, 120, 99, 42, 7, 0, 222, 43]);
const hash = value => createHash("sha256").update(value).digest("hex");
const entries = () => [
  { key: KEY_ONE, size: B1.length, sha256: hash(B1) },
  { key: KEY_TWO, size: B2.length, sha256: hash(B2) },
];
const options = (rootDir, inventory = entries()) => ({
  rootDir, inventory, sourceSnapshot: SNAP, restoredSnapshot: SNAP,
  snapshotFenceVerified: true, offlineQuarantineVerified: true,
});
async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), "ulc-k2-media-proof-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const contents = join(root, "contents");
  for (const [key, bytes] of [[KEY_ONE, B1], [KEY_TWO, B2]]) {
    const path = join(contents, ...key.split("/"));
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, bytes, { mode: 0o600 });
  }
  return { root, contents };
}
const blocked = async task => {
  await assert.rejects(task, error => {
    assert.ok(error instanceof K2OfflineMediaRecoveryError || error.name === "K2MediaInventoryError");
    assert.doesNotMatch(error.message, /exercise-1|media-1|ulc-linz/);
    return true;
  });
};

test("K2: AES-256-GCM private-media archive really decrypts, extracts and matches both recovered byte streams", async t => {
  const { root, contents } = await fixture(t);
  const archive = join(root, "backup.tar");
  const encrypted = join(root, "backup.tar.aesgcm");
  const extracted = join(root, "quarantine");
  const decrypted = join(root, "decrypt.tar");
  await exec("tar", ["-C", contents, "-cf", archive, "exercise-catalog"]);
  await encryptM4BackupFile({ inputPath: archive, outputPath: encrypted, keyHex: KEY });
  await rm(archive);
  await rm(contents, { recursive: true });
  await decryptM4BackupFile({ inputPath: encrypted, outputPath: decrypted, keyHex: KEY });
  await mkdir(extracted);
  // Only a synthetic tar generated by this test is extracted. The proof
  // library itself deliberately does not unpack untrusted archives.
  await exec("tar", ["-xf", decrypted, "-C", extracted]);
  const result = await verify(options(extracted));
  assert.deepEqual(result, {
    status: "offline-bytes-match-only",
    filesVerified: 2,
    bytesVerified: B1.length + B2.length,
    contentHashesMatched: true,
    offlineDirectoryParity: true,
    providerBackupVerified: false,
    mediaRestoreVerified: false,
    productionReady: false,
  });
  assert.deepEqual(await readFile(join(extracted, ...KEY_ONE.split("/"))), B1);
  assert.deepEqual(await readFile(join(extracted, ...KEY_TWO.split("/"))), B2);
});

test("K2: same-length modified bytes must fail, not just size-match", async t => {
  const { contents } = await fixture(t);
  await writeFile(join(contents, ...KEY_ONE.split("/")), Buffer.alloc(B1.length, 0x60));
  await blocked(() => verify(options(contents)));
});

test("K2: missing, unexpected or substituted object is not a valid media recovery", async t => {
  const { contents } = await fixture(t);
  const a = join(contents, ...KEY_ONE.split("/"));
  await unlink(a);
  await blocked(() => verify(options(contents)));
  await writeFile(a, B1);
  const extra = join(contents, "exercise-catalog", "ulc-linz", "exercise-1", "unknown");
  await writeFile(extra, "unlisted");
  await blocked(() => verify(options(contents)));
});

test("K2: symlinks and hardlinks are rejected even if the bytes match", async t => {
  const { root, contents } = await fixture(t);
  const a = join(contents, ...KEY_ONE.split("/"));
  const alternate = join(root, "alternate");
  await copyFile(a, alternate);
  await unlink(a);
  await symlink(alternate, a);
  await blocked(() => verify(options(contents)));
  await unlink(a);
  await link(alternate, a);
  await blocked(() => verify(options(contents)));
});

test("K2: snapshot fence and independent offline isolation are mandatory", async t => {
  const { contents } = await fixture(t);
  for (const override of [
    { offlineQuarantineVerified: false },
    { snapshotFenceVerified: false },
    { restoredSnapshot: "different" },
    { sourceSnapshot: "" },
    { sourceSnapshot: "customer/privacy/secret" },
  ]) await blocked(() => verify({ ...options(contents), ...override }));
});

test("K2: invalid manifest keys, hashes, duplicate keys and ETag-as-digest are rejected", async t => {
  const { contents } = await fixture(t);
  for (const inventory of [
    [...entries(), entries()[0]],
    [{ ...entries()[0], key: "../../secrets" }],
    [{ ...entries()[0], sha256: "W/123etag" }],
    [{ ...entries()[0], size: -1 }],
  ]) await blocked(() => verify(options(contents, inventory)));
});

test("K2: empty local archive is never called a real media restore", async t => {
  const { root } = await fixture(t);
  const empty = join(root, "empty");
  await mkdir(empty);
  const result = await verify(options(empty, []));
  assert.equal(result.filesVerified, 0);
  assert.equal(result.status, "empty-inventory-only");
  assert.equal(result.mediaRestoreVerified, false);
  assert.equal(result.productionReady, false);
});

test("K2: no provider or database interfaces are present in media byte proof", async () => {
  const code = await readFile(new URL("./ulc-linz-k2-offline-media-recovery.mjs", import.meta.url), "utf8");
  assert.doesNotMatch(code, /\b(?:fetch|putObject|deleteObject|aws|wrangler|neon|http\.request)\s*\(/i);
  assert.doesNotMatch(code, /(?:s3api|new\s+Client|DATABASE_URL|CLOUDFLARE_API_TOKEN)/);
});
